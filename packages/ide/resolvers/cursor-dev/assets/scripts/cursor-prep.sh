#!/usr/bin/env bash
# Host prep: Cursor desktop hints + AI agent / MCP quickstart (no remote Cursor server).
set -euo pipefail

ROOT="$(pwd)"
dockpipe_bin="${DOCKPIPE_BIN:-$(command -v dockpipe || true)}"
[[ -n "$dockpipe_bin" && -x "$dockpipe_bin" ]] || { echo "Set DOCKPIPE_BIN to an installed executable" >&2; exit 1; }
STATE_ROOT="$("$dockpipe_bin" __state package-runtime --workdir "$ROOT" --owner ide/resolver/cursor-dev --ensure-private)"
DIR="$STATE_ROOT"
mkdir -p "$DIR"

cat > "$DIR/README.txt" <<EOF
cursor-dev (Dockpipe)

Project root (host): ${ROOT}

This folder is written by the cursor-dev resolver for any workflow that runs cursor-prep
(experimental Cursor + Docker session, AI agent hints).

Dockpipe does not install a "Cursor server". Use the Cursor desktop app and open this folder.

Container sessions mount this directory at /work when you use cursor-dev with Docker.

For AI assistants and MCP setup, read: ${DIR}/AGENT-MCP.md
EOF

cat > "$DIR/AGENT-MCP.md" <<EOF
# Cursor + Dockpipe — AI agent and MCP

**This project root:** \`${ROOT}\`

This file is generated by **cursor-dev** so agents and humans share the same facts: where the repo lives, how Dockpipe/MCP relate, and what to configure in Cursor.

## What cursor-dev does here

- **Host:** open this folder in Cursor (File → Open Folder). Your tree is the source of truth.
- **Containers:** when you run \`dockpipe\` with the cursor-dev resolver and Docker, this directory is typically mounted at \`/work\` inside the session container.
- **\`DOCKPIPE_WORKDIR\`:** should point at the project you want Dockpipe and Cursor to operate on. For work in this tree, use: \`${ROOT}\`.

## MCP (Model Context Protocol) — \`mcpd\`

[DorkPipe](https://github.com/Dockpipe-Industries/dorkpipe) owns the MCP bridge and
agent tools. Install its published package or follow its own build workflows.
Dockpipe remains the installed runtime used by this project.

1. Install Dockpipe, DorkPipe and the MCP bridge from their owning distributions.
2. Set the MCP command to the absolute installed \`mcpd\` executable.
3. Set \`DOCKPIPE_BIN\` and \`DORKPIPE_BIN\` to their absolute installed paths.
4. Enable MCP in Cursor and merge \`${DIR}/mcp.json.example\` into the project configuration.
5. Restart Cursor after editing MCP configuration.

Set \`MCPD_BIN\` and \`DORKPIPE_BIN\` before running this resolver to prefill those
paths. Missing tools retain explicit placeholders in the generated example.

Runtime documentation: https://github.com/Dockpipe-Industries/dockpipe/tree/master/docs
Agent and MCP documentation: https://github.com/Dockpipe-Industries/dorkpipe

EOF

MCPD_CONFIG_BIN="${MCPD_BIN:-$(command -v mcpd || true)}" \
DORKPIPE_CONFIG_BIN="${DORKPIPE_BIN:-$(command -v dorkpipe || true)}" \
DOCKPIPE_CONFIG_BIN="$dockpipe_bin" \
python3 - "$DIR/mcp.json.example" <<'PYJSON'
import json
import os
import sys

configuration = {
    "mcpServers": {
        "dockpipe": {
            "command": os.environ["MCPD_CONFIG_BIN"] or "/absolute/path/to/mcpd",
            "args": [],
            "env": {
                "DOCKPIPE_BIN": os.environ["DOCKPIPE_CONFIG_BIN"],
                "DORKPIPE_BIN": os.environ["DORKPIPE_CONFIG_BIN"] or "/absolute/path/to/dorkpipe",
            },
        },
    },
}
with open(sys.argv[1], "w", encoding="utf-8") as output:
    json.dump(configuration, output, indent=2)
    output.write("\n")
PYJSON

printf '[dockpipe] Wrote %s (AI agent + MCP: %s)\n' "$DIR/README.txt" "$DIR/AGENT-MCP.md" >&2
if [[ -f "$DIR/mcp.json.example" ]]; then
  printf '[dockpipe] Wrote %s\n' "$DIR/mcp.json.example" >&2
fi
